	if ID==0 then
		if EN==0 then
			PPMU.RELAY_EN(27)
			PPMU.RELAY_EN(28)
		elseif EN==1 then
			PPMU.RELAY_CLOSE(27)
			PPMU.RELAY_CLOSE(28)

		end
	elseif ID==1 then

		if EN==0 then
			PPMU.RELAY_EN(29)
			PPMU.RELAY_EN(30)
		elseif EN==1 then
			PPMU.RELAY_CLOSE(29)
			PPMU.RELAY_CLOSE(30)
		end
	
	end

end