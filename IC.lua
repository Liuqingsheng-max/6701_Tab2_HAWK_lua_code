function Display_init(mode)

	bist_mode = (mode == nil) and 0 or mode
	if bist_mode == 0 then--1:bistmode, 0:PG
		DMIPI.VID()
		TIME.DELAY(10)
		DMIPI.HS() --VIDEO Using
		F_28M2_I2C_Initial_MIPI()
		LOG.INFO("do mipi")
	else
		F_28M2_I2C_Initial()
		LOG.INFO("do VPG")
	end
end

